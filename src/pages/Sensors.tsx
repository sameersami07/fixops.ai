import React, { useState, useEffect, useRef } from 'react';
import { Activity, Thermometer, AlertTriangle, RefreshCw, CheckCircle, ClipboardList } from 'lucide-react';
import {
  LineChart, Line, XAxis, YAxis, CartesianGrid, Tooltip, ResponsiveContainer, ReferenceLine
} from 'recharts';
import { Layout, Header } from '../components/layout/Layout';
import { Card, Button, SectionHeader, Badge } from '../components/ui';
import { useApp } from '../contexts/AppContext';
import { getEquipmentStatusConfig, getHealthScoreConfig, generateId } from '../utils';

interface SensorPoint {
  time: string;
  temperature: number;
  vibration: number;
}

function generateReading(base: number, range: number) {
  return +(base + (Math.random() - 0.5) * range * 2).toFixed(1);
}

export default function SensorsPage() {
  const { equipment, alerts, addAlert, acknowledgeAlert } = useApp();
  const [selectedEquipment, setSelectedEquipment] = useState(equipment[0]?.id || '');
  const [sensorData, setSensorData] = useState<Record<string, SensorPoint[]>>({});
  const [isSimulating, setIsSimulating] = useState(true);
  const [tick, setTick] = useState(0);
  const intervalRef = useRef<ReturnType<typeof setInterval> | undefined>(undefined);

  const operationalEquipment = equipment.filter(e => e.status !== 'OFFLINE');

  const getCurrentReading = (equipmentId: string) => {
    const data = sensorData[equipmentId];
    return data?.[data.length - 1];
  };

  const selectedEq = equipment.find(e => e.id === selectedEquipment);
  const selectedData = sensorData[selectedEquipment] || [];

  useEffect(() => {
    if (!isSimulating) { clearInterval(intervalRef.current); return; }
    intervalRef.current = setInterval(() => {
      const now = new Date().toLocaleTimeString('en-IN', { hour: '2-digit', minute: '2-digit', second: '2-digit' });
      setSensorData(prev => {
        const next = { ...prev };
        operationalEquipment.forEach(eq => {
          const existing = prev[eq.id] || [];
          const newPoint: SensorPoint = {
            time: now,
            temperature: generateReading(eq.currentTemperature, 5),
            vibration: generateReading(eq.currentVibration, 0.8),
          };
          next[eq.id] = [...existing.slice(-29), newPoint];
        });
        return next;
      });
      setTick(t => t + 1);
    }, 2000);
    return () => clearInterval(intervalRef.current);
  }, [isSimulating, operationalEquipment.length]);

  // Check thresholds and generate alerts
  useEffect(() => {
    if (tick === 0) return;
    operationalEquipment.forEach(eq => {
      const reading = getCurrentReading(eq.id);
      if (!reading) return;
      if (reading.temperature > eq.temperatureThreshold) {
        const alreadyExists = alerts.some(a => a.equipmentId === eq.id && a.type === 'TEMPERATURE' && !a.isAcknowledged && Date.now() - new Date(a.createdAt).getTime() < 30000);
        if (!alreadyExists) {
          addAlert({
            id: generateId('al'), title: `Temperature Alert: ${eq.name}`,
            message: `Temperature ${reading.temperature}°C exceeds threshold of ${eq.temperatureThreshold}°C (Simulated)`,
            equipmentId: eq.id, equipmentName: eq.name, severity: 'HIGH',
            type: 'TEMPERATURE', isRead: false, isAcknowledged: false, createdAt: new Date().toISOString(),
          });
        }
      }
    });
  }, [tick]);

  return (
    <Layout>
      <Header
        title="Sensor Monitor"
        subtitle="Real-time equipment sensor monitoring (Simulated)"
        actions={
          <div className="flex items-center gap-3">
            <span className="badge badge-yellow text-xs">📡 Simulated Data</span>
            <Button
              variant={isSimulating ? 'danger' : 'primary'}
              size="sm"
              leftIcon={isSimulating ? <AlertTriangle className="w-3.5 h-3.5" /> : <RefreshCw className="w-3.5 h-3.5" />}
              onClick={() => setIsSimulating(!isSimulating)}
            >
              {isSimulating ? 'Stop Simulation' : 'Start Simulation'}
            </Button>
          </div>
        }
      />

      <div className="p-6 space-y-4">
        {/* Disclaimer */}
        <div className="alert-strip-blue">
          <AlertTriangle className="w-4 h-4 flex-shrink-0" />
          <p className="text-xs">
            📡 <strong>Simulated Sensor Data:</strong> All readings are generated by the sensor simulator for demonstration. 
            In production, this connects to real IoT sensors via MQTT broker, REST APIs, or OPC-UA protocols.
          </p>
        </div>

        {/* Equipment Status Grid */}
        <div className="grid grid-cols-2 lg:grid-cols-5 gap-3">
          {operationalEquipment.slice(0, 5).map(eq => {
            const reading = getCurrentReading(eq.id);
            const tempAlert = reading && reading.temperature > eq.temperatureThreshold;
            const vibAlert = reading && reading.vibration > eq.vibrationThreshold;
            const hasAlert = tempAlert || vibAlert;
            const status = getEquipmentStatusConfig(eq.status);
            const health = getHealthScoreConfig(eq.healthScore);

            return (
              <button
                key={eq.id}
                onClick={() => setSelectedEquipment(eq.id)}
                className={`text-left p-3.5 rounded-xl border transition-all ${selectedEquipment === eq.id ? 'border-blue-400 bg-blue-50 shadow-md' : hasAlert ? 'border-red-300 bg-red-50' : 'border-slate-200 bg-white hover:border-blue-200 hover:bg-slate-50'}`}
              >
                <div className="flex items-center justify-between mb-2">
                  <span className="text-[9px] font-mono text-slate-400">{eq.code}</span>
                  {hasAlert && <span className="text-red-500 animate-pulse">⚠</span>}
                  {!hasAlert && isSimulating && <span className="w-1.5 h-1.5 bg-emerald-400 rounded-full animate-pulse" />}
                </div>
                <p className="text-xs font-semibold text-slate-800 leading-tight mb-2">{eq.name.split('#')[0].trim()}</p>
                {reading ? (
                  <div className="space-y-1">
                    <div className={`text-xs font-bold flex items-center gap-1 ${tempAlert ? 'text-red-600' : 'text-slate-700'}`}>
                      <Thermometer className="w-3 h-3" />{reading.temperature}°C
                    </div>
                    <div className={`text-xs font-bold flex items-center gap-1 ${vibAlert ? 'text-red-600' : 'text-slate-700'}`}>
                      <Activity className="w-3 h-3" />{reading.vibration} mm/s
                    </div>
                  </div>
                ) : (
                  <div className="text-xs text-slate-400">Starting...</div>
                )}
              </button>
            );
          })}
        </div>

        {/* Selected Equipment Detail */}
        {selectedEq && (
          <div className="grid lg:grid-cols-3 gap-4">
            {/* Equipment Info */}
            <Card>
              <SectionHeader title={selectedEq.name} subtitle={selectedEq.code} />
              <div className="space-y-3">
                {(() => {
                  const reading = getCurrentReading(selectedEq.id);
                  const health = getHealthScoreConfig(selectedEq.healthScore);
                  const tempAlert = reading && reading.temperature > selectedEq.temperatureThreshold;
                  const vibAlert = reading && reading.vibration > selectedEq.vibrationThreshold;
                  return (
                    <>
                      <div className="grid grid-cols-2 gap-3">
                        <div className={`p-3 rounded-lg border ${tempAlert ? 'bg-red-50 border-red-200' : 'bg-slate-50 border-slate-100'}`}>
                          <div className="flex items-center gap-1.5 mb-1">
                            <Thermometer className={`w-3.5 h-3.5 ${tempAlert ? 'text-red-500' : 'text-slate-400'}`} />
                            <span className="text-xs text-slate-500">Temperature</span>
                          </div>
                          <p className={`text-xl font-bold ${tempAlert ? 'text-red-600' : 'text-slate-900'}`}>
                            {reading ? `${reading.temperature}°C` : '—'}
                          </p>
                          <p className="text-[10px] text-slate-400">Limit: {selectedEq.temperatureThreshold}°C</p>
                          {tempAlert && <p className="text-[10px] text-red-600 font-semibold">⚠ EXCEEDED</p>}
                        </div>
                        <div className={`p-3 rounded-lg border ${vibAlert ? 'bg-red-50 border-red-200' : 'bg-slate-50 border-slate-100'}`}>
                          <div className="flex items-center gap-1.5 mb-1">
                            <Activity className={`w-3.5 h-3.5 ${vibAlert ? 'text-red-500' : 'text-slate-400'}`} />
                            <span className="text-xs text-slate-500">Vibration</span>
                          </div>
                          <p className={`text-xl font-bold ${vibAlert ? 'text-red-600' : 'text-slate-900'}`}>
                            {reading ? `${reading.vibration}` : '—'}
                          </p>
                          <p className="text-[10px] text-slate-400">Limit: {selectedEq.vibrationThreshold} mm/s</p>
                          {vibAlert && <p className="text-[10px] text-red-600 font-semibold">⚠ EXCEEDED</p>}
                        </div>
                      </div>

                      <div>
                        <div className="flex justify-between text-xs mb-1">
                          <span className="text-slate-500">Health Score</span>
                          <span className={`font-bold ${health.color}`}>{selectedEq.healthScore}% ({health.label})</span>
                        </div>
                        <div className="h-2.5 bg-slate-100 rounded-full overflow-hidden">
                          <div className={`h-full rounded-full transition-all ${health.bar}`} style={{ width: `${selectedEq.healthScore}%` }} />
                        </div>
                      </div>

                      <div className="space-y-2">
                        <div className="flex justify-between text-xs">
                          <span className="text-slate-500">Status</span>
                          <span className={`font-semibold ${getEquipmentStatusConfig(selectedEq.status).text}`}>{getEquipmentStatusConfig(selectedEq.status).label}</span>
                        </div>
                        <div className="flex justify-between text-xs">
                          <span className="text-slate-500">Location</span>
                          <span className="text-slate-700">{selectedEq.location}</span>
                        </div>
                        <div className="flex justify-between text-xs">
                          <span className="text-slate-500">Category</span>
                          <span className="text-slate-700">{selectedEq.category}</span>
                        </div>
                        <div className="flex justify-between text-xs">
                          <span className="text-slate-500">Simulation</span>
                          <span className={isSimulating ? 'text-emerald-600 font-semibold' : 'text-red-500'}>
                            {isSimulating ? '● Running' : '○ Stopped'}
                          </span>
                        </div>
                      </div>
                    </>
                  );
                })()}
              </div>
            </Card>

            {/* Charts */}
            <Card className="lg:col-span-2">
              <SectionHeader
                title="Live Sensor Readings"
                subtitle={`${selectedData.length} data points (updating every 2s)`}
                action={<span className="text-xs text-slate-400">{isSimulating ? '🟢 Live' : '⚪ Paused'}</span>}
              />
              <div className="space-y-4">
                <div>
                  <p className="text-xs text-slate-500 mb-2">Temperature (°C)</p>
                  <ResponsiveContainer width="100%" height={150}>
                    <LineChart data={selectedData}>
                      <CartesianGrid strokeDasharray="3 3" stroke="#f1f5f9" />
                      <XAxis dataKey="time" tick={{ fontSize: 9, fill: '#94a3b8' }} tickLine={false} interval="preserveStartEnd" />
                      <YAxis tick={{ fontSize: 9, fill: '#94a3b8' }} tickLine={false} domain={['auto', 'auto']} />
                      <Tooltip contentStyle={{ fontSize: '11px', borderRadius: '8px', border: '1px solid #e2e8f0' }} />
                      {selectedEq && <ReferenceLine y={selectedEq.temperatureThreshold} stroke="#ef4444" strokeDasharray="4 4" strokeWidth={1} />}
                      <Line type="monotone" dataKey="temperature" stroke="#3b82f6" strokeWidth={2} dot={false} name="Temp °C" isAnimationActive={false} />
                    </LineChart>
                  </ResponsiveContainer>
                </div>
                <div>
                  <p className="text-xs text-slate-500 mb-2">Vibration (mm/s)</p>
                  <ResponsiveContainer width="100%" height={150}>
                    <LineChart data={selectedData}>
                      <CartesianGrid strokeDasharray="3 3" stroke="#f1f5f9" />
                      <XAxis dataKey="time" tick={{ fontSize: 9, fill: '#94a3b8' }} tickLine={false} interval="preserveStartEnd" />
                      <YAxis tick={{ fontSize: 9, fill: '#94a3b8' }} tickLine={false} domain={[0, 'auto']} />
                      <Tooltip contentStyle={{ fontSize: '11px', borderRadius: '8px', border: '1px solid #e2e8f0' }} />
                      {selectedEq && <ReferenceLine y={selectedEq.vibrationThreshold} stroke="#ef4444" strokeDasharray="4 4" strokeWidth={1} />}
                      <Line type="monotone" dataKey="vibration" stroke="#7c3aed" strokeWidth={2} dot={false} name="Vibration mm/s" isAnimationActive={false} />
                    </LineChart>
                  </ResponsiveContainer>
                </div>
              </div>
            </Card>
          </div>
        )}

        {/* All Equipment Summary Table */}
        <Card padding={false}>
          <div className="p-4 border-b border-slate-100">
            <h3 className="text-sm font-semibold text-slate-900">All Equipment Readings</h3>
            <p className="text-xs text-slate-500">Live sensor status overview</p>
          </div>
          <div className="overflow-x-auto">
            <table className="data-table">
              <thead>
                <tr>
                  <th>Equipment</th>
                  <th>Status</th>
                  <th>Temperature</th>
                  <th>Temp Threshold</th>
                  <th>Vibration</th>
                  <th>Vib Threshold</th>
                  <th>Health</th>
                  <th>Alerts</th>
                </tr>
              </thead>
              <tbody>
                {equipment.map(eq => {
                  const reading = getCurrentReading(eq.id);
                  const status = getEquipmentStatusConfig(eq.status);
                  const health = getHealthScoreConfig(eq.healthScore);
                  const tempAlert = reading && reading.temperature > eq.temperatureThreshold;
                  const vibAlert = reading && reading.vibration > eq.vibrationThreshold;
                  return (
                    <tr key={eq.id} className={`cursor-pointer ${selectedEquipment === eq.id ? 'bg-blue-50' : ''}`}
                      onClick={() => setSelectedEquipment(eq.id)}>
                      <td>
                        <div>
                          <p className="font-semibold text-slate-800 text-sm">{eq.name}</p>
                          <p className="text-xs font-mono text-slate-400">{eq.code}</p>
                        </div>
                      </td>
                      <td>
                        <span className={`badge ${status.color}`}>
                          <span className={`status-dot ${status.dot}`} />{status.label}
                        </span>
                      </td>
                      <td>
                        {eq.status === 'OFFLINE' ? <span className="text-slate-400 text-xs">Offline</span> : (
                          <span className={`text-sm font-semibold ${tempAlert ? 'text-red-600' : 'text-slate-700'}`}>
                            {reading ? `${reading.temperature}°C` : eq.currentTemperature.toFixed(1) + '°C'}
                            {tempAlert && ' ⚠'}
                          </span>
                        )}
                      </td>
                      <td className="text-xs text-slate-500">{eq.temperatureThreshold}°C</td>
                      <td>
                        {eq.status === 'OFFLINE' ? <span className="text-slate-400 text-xs">Offline</span> : (
                          <span className={`text-sm font-semibold ${vibAlert ? 'text-red-600' : 'text-slate-700'}`}>
                            {reading ? `${reading.vibration} mm/s` : eq.currentVibration.toFixed(1) + ' mm/s'}
                            {vibAlert && ' ⚠'}
                          </span>
                        )}
                      </td>
                      <td className="text-xs text-slate-500">{eq.vibrationThreshold} mm/s</td>
                      <td>
                        <div className="flex items-center gap-2">
                          <div className="w-14 h-1.5 bg-slate-100 rounded-full overflow-hidden">
                            <div className={`h-full rounded-full ${health.bar}`} style={{ width: `${eq.healthScore}%` }} />
                          </div>
                          <span className={`text-xs font-bold ${health.color}`}>{eq.healthScore}%</span>
                        </div>
                      </td>
                      <td>
                        {(tempAlert || vibAlert) ? (
                          <span className="badge badge-red text-[10px] animate-pulse">Alert!</span>
                        ) : eq.status === 'OFFLINE' ? (
                          <span className="badge badge-gray text-[10px]">Offline</span>
                        ) : (
                          <span className="flex items-center gap-1 text-emerald-600">
                            <CheckCircle className="w-3.5 h-3.5" />
                            <span className="text-xs">Normal</span>
                          </span>
                        )}
                      </td>
                    </tr>
                  );
                })}
              </tbody>
            </table>
          </div>
        </Card>
      </div>
    </Layout>
  );
}
